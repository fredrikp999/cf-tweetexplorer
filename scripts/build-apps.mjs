// Bundles each MCP App view (src/apps/<name>.ts + its CSS) into a single HTML string module, src/apps/<name>.html.ts.
// A host serves the view from a ui:// resource and blocks external loads by default, so everything is inlined.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const CSS = `
:root{color-scheme:light dark;--bg:#fff;--fg:#1a1a1a;--mut:#6b6b6b;--bar:#2f6fed;--line:#e2e2e2}
:root[data-theme=dark]{--bg:#1c1c1e;--fg:#f2f2f2;--mut:#9a9a9a;--bar:#6a9bff;--line:#38383a}
body{margin:0;padding:16px;background:var(--bg);color:var(--fg);font:14px/1.4 system-ui,sans-serif}
h1{margin:0;font-size:26px}h1 small{font-size:13px;font-weight:400;color:var(--mut)}.sub{margin:4px 0 16px;color:var(--mut)}
.chart{display:flex;align-items:flex-end;gap:2px;height:90px;margin-bottom:16px}.bar{flex:1;background:var(--bar);border-radius:2px 2px 0 0;min-width:2px}
table{width:100%;border-collapse:collapse}th,td{text-align:right;padding:6px 8px;border-bottom:1px solid var(--line)}th:first-child,td:first-child{text-align:left}th{color:var(--mut);font-weight:500}`;

for (const name of ['costs']) {
  const out = await build({ entryPoints: [`src/apps/${name}.ts`], bundle: true, write: false, format: 'esm', target: 'es2022', minify: true });
  const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${CSS}</style></head><body><div id="root">Loading…</div><script type="module">${js}</script></body></html>`;
  writeFileSync(`src/apps/${name}.html.ts`, `// Generated by scripts/build-apps.mjs from src/apps/${name}.ts. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
}
